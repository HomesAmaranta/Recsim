def ask(prompt):
    """询问确认。yes 继续，其余退出。"""
    while True:
        try:
            ans = input(f"{prompt} [yes/no]: ").strip().lower()
        except (EOFError, KeyboardInterrupt):
            print("\n已取消，退出测试。")
            sys.exit(1)
        if ans in ("yes", "y"):
            return True
        if ans in ("no", "n"):
            print("已取消，退出测试。")
            sys.exit(0)
        print("  请输入 yes 或 no")


def progress(label, seconds=1.0, steps=34):
    """进度条。总耗时 seconds 秒。"""
    delay = seconds / steps
    for i in range(steps + 1):
        pct = i * 100 // steps
        bar = "█" * i + "░" * (steps - i)
        sys.stdout.write(f"\r  {label} |{bar}| {pct:3d}%")
        sys.stdout.flush()
        time.sleep(delay)
    print()


def step(msg, seconds=1.0):
    """单行步骤 + 省略号动画。"""
    sys.stdout.write(f"  {msg}")
    sys.stdout.flush()
    n = max(int(seconds / 0.25), 1)
    for _ in range(n):
        sys.stdout.write(".")
        sys.stdout.flush()
        time.sleep(0.25)
    print("  [OK]")


def rule(title=""):
    if title:
        print("\n" + "=" * 78)
        print(title)
        print("=" * 78)
    else:
        print("-" * 78)


